/// Drop only the never-surfaced turns; collapsed markers stay in the list.
pub fn drop_hidden_messages(messages: &[ChatMessage]) -> Vec<ChatMessage> {
    messages
        .iter()
        .filter(|message| !is_hidden_message(message))
        .cloned()
        .collect()
}

fn fits_inline_suppressed_turn(body: &str) -> bool {
    !body.is_empty()
        && crate::transcript::jsstr::utf16_len(body) <= INLINE_BODY_MAX_CHARS
        && body.split('\n').count() <= INLINE_BODY_MAX_LINES
}

/// What a status row is about, so each renderer leads it with a fitting glyph: a background
/// `task`, a context `compaction`, or a `setting` the reader changed (model, effort, Fast mode).
fn status_subject(label: &str) -> &'static str {
    match label {
        CONTEXT_COMPACTED_LABEL | COMPACTION_COMPLETED_LABEL | NOTHING_TO_COMPRESS_LABEL => {
            "compaction"
        }
        _ => "setting",
    }
}

fn status_row_value(row: &StatusRow) -> Value {
    let mut entry = Map::new();
    entry.insert("label".to_string(), row.label.clone().into());
    entry.insert("tone".to_string(), row.tone.into());
    if let Some(detail) = &row.detail {
        entry.insert("detail".to_string(), detail.clone().into());
    }
    Value::Object(entry)
}

/// Human-readable label and expandable text for a suppressed harness turn, or `Value::Null`.
///
/// `kind` is `collapsed`, `inline` (a short collapsed turn shown as prose instead of a chevron) or
/// `status`.
pub fn suppressed_turn_presentation(message: &ChatMessage) -> Value {
    let suppressed = classify_suppressed_turn(message);
    let (kind, label, tone) = match &suppressed {
        Some(SuppressedTurn::Collapsed { label }) => ("collapsed", label.clone(), None),
        Some(SuppressedTurn::Status { label, tone }) => ("status", label.clone(), *tone),
        _ => return Value::Null,
    };

    if kind == "collapsed" && label == INTERRUPTED_LABEL {
        return json!({ "kind": "inline", "label": INTERRUPTED_MARKER_TEXT, "text": "" });
    }

    // A background task's end never gets here: it is projected as the tool call it reports
    // (`background_rows.rs`).
    let raw_text = js_trim(&joined_text(&message.blocks)).to_string();

    let command = parse_command_envelope(&raw_text);
    let model = model_set_by_command_output(&raw_text);
    let is_local_command = label == "Local command" || label == "Local command output";
    let body = if is_local_command {
        suppressed_turn_body(&raw_text)
    } else {
        raw_text.clone()
    };
    let mut text = strip_ansi(&body);
    if command
        .as_ref()
        .map(|envelope| ascii_lower(&envelope.name))
        .as_deref()
        == Some("/model")
    {
        text = command.expect("a matched name implies an envelope").name;
    } else if let Some(model) = &model {
        text = normalized_suppressed_turn_body(&raw_text);
        if let Some(note) = &model.note {
            // The pin warning is a second fact about the same action, not chrome to drop: it gets
            // its own neutral row under the model result.
            let statuses = vec![
                status_row_value(&StatusRow {
                    label: label.clone(),
                    tone: if kind == "status" {
                        tone.unwrap_or("ok")
                    } else {
                        "ok"
                    },
                    detail: None,
                }),
                json!({ "label": note, "tone": "neutral" }),
            ];
            return json!({
                "kind": "status",
                "subject": "setting",
                "label": label,
                "text": text,
                "statuses": statuses,
            });
        }
    }

    if kind == "collapsed" && label == "Local command output" {
        return command_output_note(&raw_text);
    }

    // Short harness turns read as prose; the body without its markup IS the sentence, so the inline
    // row shows that rather than the raw envelope.
    if kind == "collapsed" {
        let body = strip_ansi(&suppressed_turn_body(&raw_text));
        if fits_inline_suppressed_turn(&body) {
            return json!({ "kind": "inline", "label": label, "text": body });
        }
    }

    let mut out = Map::new();
    out.insert("kind".to_string(), kind.into());
    if kind == "status" {
        out.insert("subject".to_string(), status_subject(&label).into());
    }
    out.insert("label".to_string(), label.into());
    out.insert("text".to_string(), text.into());
    if kind == "status" {
        if let Some(tone) = tone {
            out.insert("tone".to_string(), tone.into());
        }
    }
    Value::Object(out)
}

/// CDXC:SessionChat 2026-11-02 DECISION:
/// User, about the grey "Local command output · Session renamed to: …" row under a slash command: "i dont like how these look, they dont look like the other parts of the chat transcript". They picked "D. Your bubble, then a note" for every agent: what a slash command printed (Claude's `<local-command-stdout>`, gxserver's archived output for every other agent) is a quiet status note like the compaction and model-change rows, not a grey marker. The note shows the output's first line; output with more lines opens to the whole of it on click (`expandable`). Only stderr reads as an error. The command itself is the user's bubble above it (`surface_skill_invocation_user_turns`).
/// SEE-ALSO: apps/desktop/src/app/native_chat/status_rows.rs, apps/mobile/app/src/chat/native/transcript/SystemRows.tsx.
fn command_output_note(raw_text: &str) -> Value {
    let body = js_trim(&strip_ansi(&suppressed_turn_body(raw_text))).to_string();
    let first_line = split_newlines(&body)
        .into_iter()
        .map(js_trim)
        .find(|line| !line.is_empty())
        .unwrap_or_default()
        .to_string();
    let expandable = body
        .lines()
        .filter(|line| !js_trim(line).is_empty())
        .count()
        > 1;
    let stderr_only = ascii_lower(js_trim_start(raw_text)).starts_with("<local-command-stderr")
        && !raw_text.contains("<local-command-stdout");
    json!({
        "kind": "status",
        "subject": "command",
        "label": first_line,
        "text": if expandable { body } else { String::new() },
        "tone": if stderr_only { "error" } else { "neutral" },
        "expandable": expandable,
    })
}
