/// Harness tags that render as a collapsed, expandable marker.
fn collapsed_tag_label(tag: &str) -> Option<&'static str> {
    Some(match tag {
        "agent-message" => "Message from another session",
        "bash-input" => "Local command",
        "bash-stderr" | "bash-stdout" => "Local command output",
        "command-args" | "command-message" | "command-name" => "Slash command",
        "cross-session-message" => "Message from another session",
        "local-command-caveat" | "local-command-stderr" | "local-command-stdout" => {
            "Local command output"
        }
        "task-notification" => "Task notification",
        "teammate-message" => "Message from another session",
        "user-memory-input" => "Memory note",
        _ => return None,
    })
}

/// Harness tags the agent's own TUI never prints either: they stay hidden.
