//! The harness-injected turn classifier.
//!
//! Ported from `packages/core-ui/chat/session-chat-noise.ts`, tag and prefix constants verbatim.
//!
//! Design law (do not "improve" this): match only tags OBSERVED from harnesses, never a broad kebab
//! shape. A real prompt starting with a custom `<my-element>` or a Grok `<user_query>` envelope is a
//! genuine user turn; misclassifying it hides the turn. `<channel>` is only matched in its
//! attributed `<channel source=` form, because a bare `<channel>` is a real RSS or XML paste.
//!
//! Second law: a matched turn is SUPPRESSED, not deleted. Everything the terminal itself prints
//! renders as a one-line collapsed marker that expands to the full text; deleting them is exactly
//! what reads as "chat is missing messages". Only the records the terminal never shows either
//! (system reminders, hook plumbing) stay hidden.

