/// `pickSessionChatWorkingWord`: `words[Math.floor(random * words.length)] ?? 'Working'`.
///
/// `random_unit` is the host's draw for this turn, in `[0, 1)`. An out-of-range draw falls back to
/// `Working`, the same way the TypeScript's `??` does on an out-of-range index.
pub fn pick_working_word(random_unit: f64) -> &'static str {
    let index = (random_unit * SESSION_CHAT_WORKING_WORDS.len() as f64).floor();
    if !index.is_finite() || index < 0.0 {
        return "Working";
    }
    SESSION_CHAT_WORKING_WORDS
        .get(index as usize)
        .copied()
        .unwrap_or("Working")
}
