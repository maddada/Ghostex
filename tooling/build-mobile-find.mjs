#!/usr/bin/env node
/*
CDXC:AgentHistorySearch 2026-08-20:
Bundles apps/mobile/views/find/find-prompts-main.tsx (the shared Find page — the GUI for
`gx f` — that the React Native app hosts in a webview) into ONE self-contained
HTML document and writes it as a generated TypeScript module inside the mobile
submodule. The app imports that string and feeds it to react-native-webview as
`source={{ html }}`, which sidesteps every platform difference around bundled
file:// assets on iOS and Android. Run after changing packages/core-ui/find UI, core-ui
styles, or the mobile-find entry:

  bun run build:mobile-find
*/

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.join(repoRoot, "apps", "mobile", "views", "find", "find-prompts-main.tsx");
const outFile = path.join(repoRoot, "apps", "mobile", "app", "src", "find", "find-prompts-html.generated.ts");

/*
The app's Vite/Bun builds deliberately import SVG source text with an import
attribute. esbuild only accepts the standardized JSON value for a `type`
attribute, so remove that source-only hint in this single-file build; the SVG
dataurl loader below remains compatible with the logo helpers.
*/
const mobileFindTextImportPlugin = {
  name: "mobile-find-text-imports",
  setup(build) {
    build.onLoad(
      { filter: /core-ui\/(?:agent-logos\.ts|brand-icons\.tsx)$/ },
      async (args) => ({
        contents: (await fs.promises.readFile(args.path, "utf8")).replace(
          /\s+with\s+\{\s*type:\s*["']text["']\s*\}/g,
          "",
        ),
        loader: args.path.endsWith(".tsx") ? "tsx" : "ts",
      }),
    );
  },
};

const result = await esbuild.build({
  bundle: true,
  define: { "process.env.NODE_ENV": '"production"' },
  entryPoints: [entry],
  format: "iife",
  jsx: "automatic",
  // Inline every url() asset so the single HTML document has no external
  // references (webview html sources have no usable base URL).
  loader: {
    ".png": "dataurl",
    ".svg": "dataurl",
    ".ttf": "dataurl",
    ".woff": "dataurl",
    ".woff2": "dataurl",
  },
  minify: true,
  outdir: "out",
  plugins: [mobileFindTextImportPlugin],
  target: ["safari16", "chrome110"],
  write: false,
});

let js = "";
let css = "";
for (const file of result.outputFiles) {
  if (file.path.endsWith(".js")) js += file.text;
  else if (file.path.endsWith(".css")) css += file.text;
}
if (!js) {
  throw new Error("esbuild produced no JS output for the mobile Find page.");
}

// </script>-shaped strings inside generated JS would end the inline script tag.
const inlineJs = js.replace(/<\/script>/gi, "<\\/script>");
const inlineCss = css.replace(/<\/style>/gi, "<\\/style>");

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no, viewport-fit=cover" />
    <title>Ghostex Find Prompts</title>
    <style>
      html,
      body {
        background: #111111;
        height: 100%;
        margin: 0;
        overscroll-behavior: none;
        -webkit-text-size-adjust: 100%;
      }
    </style>
    <style>${inlineCss}</style>
  </head>
  <body>
    <div id="root"></div>
    <script>${inlineJs}</script>
  </body>
</html>
`;

const banner = `// GENERATED by tooling/build-mobile-find.mjs in the Ghostex main repo — do not
// edit by hand. Source: apps/mobile/views/find/find-prompts-main.tsx plus the shared
// packages/core-ui/find UI. Regenerate with \`bun run build:mobile-find\` there.

// eslint-disable-next-line @typescript-eslint/no-inferrable-types
export const FIND_PROMPTS_HTML: string = ${JSON.stringify(html)
  .replace(/\u2028/g, "\\u2028")
  .replace(/\u2029/g, "\\u2029")};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, banner);
const sizeKb = Math.round(Buffer.byteLength(banner) / 1024);
console.log(
  `Wrote ${path.relative(repoRoot, outFile)} (${sizeKb} KiB; js ${Math.round(js.length / 1024)} KiB, css ${Math.round(css.length / 1024)} KiB).`,
);
