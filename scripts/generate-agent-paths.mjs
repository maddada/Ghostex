#!/usr/bin/env node
// Code-generates shared/agent-paths.generated.ts from Rust AgentPaths.
// Rust is the single source of truth; this script only emits TS from JSON.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..");
const gxserverDir = join(repoRoot, "gxserver-rs");

const raw = execFileSync("cargo", ["run", "--quiet", "--bin", "generate-agent-paths"], {
  cwd: gxserverDir,
  encoding: "utf8",
});

const components = JSON.parse(raw);

function asStringLiteral(parts) {
  if (parts.length === 0) return '""';
  return JSON.stringify(parts.join("/"));
}

const lines = [
  "// AUTO-GENERATED by scripts/generate-agent-paths.mjs",
  "// Source of truth: gxserver-rs/src/paths.rs (AgentPaths)",
  "// Do not edit manually; the Rust drift test will catch differences.",
  "",
];

for (const [name, parts] of Object.entries(components)) {
  const exportName = snakeToConstant(name);
  lines.push(`export const ${exportName} = ${asStringLiteral(parts)} as const;`);
}

lines.push("");
lines.push("export const AGENT_PATH_COMPONENTS = {");
for (const [name, parts] of Object.entries(components)) {
  lines.push(`  ${name}: ${JSON.stringify(parts)},`);
}
lines.push("} as const;");
lines.push("");

writeFileSync(join(repoRoot, "shared", "agent-paths.generated.ts"), lines.join("\n"));
console.log("Generated shared/agent-paths.generated.ts");

function snakeToConstant(value) {
  return value
    .split("_")
    .map((part) => part.toUpperCase())
    .join("_");
}
